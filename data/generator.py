# ---------- helpers ----------

def fmt_date(d):
    """Дата → 'ДД.ММ.ГГГГ' или '' для пустого."""
    if d is None or d == "":
        return ""
    if isinstance(d, datetime):
        return d.strftime("%d.%m.%Y")
    if isinstance(d, date):
        return d.strftime("%d.%m.%Y")
    return str(d)


def save_xlsx(path, headers, rows):
    wb = Workbook()
    ws = wb.active
    ws.title = "Лист1"
    ws.append(headers)
    for r in rows:
        ws.append(r)
    wb.save(path)
    print(f"  -> {path} ({len(rows)} строк)")


