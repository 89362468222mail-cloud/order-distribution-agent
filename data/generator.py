def build_etalon():
    import re
    cloud_orders = {r[0] for r in CLOUD_ROWS}
    ful_orders_seen = {}
    rows = []
    for i, ful in enumerate(FUL_ROWS):
        num = ful[2]
        comment = ful[4]
        delivery = ful[5]
        country = ful[9]
        m = re.search(r"S\d{7}", comment)
        order = m.group(0) if m else "не определено"

        if order == "не определено":
            status, group, logist, reason = "требует внимания", "не определено", "не определено", "нет номера заказа"
        elif order in cloud_orders:
            status, group, logist, reason = "повторная отправка", "", "", "заказ уже есть в Cloud"
        elif order in ful_orders_seen:
            status, group, logist, reason = "повторная отправка", "", "", "дубль внутри пачки"
        else:
            status = "новый"
            if delivery == "":
                group = "не определено"
                logist = "не определено"
                reason = "нет способа доставки"
                status = "требует внимания"
            elif delivery == "air":
                group = "специалист по авиаперевозкам"
                logist = "определяется скриптом"
                reason = "air -> авиа"
            elif country in ("", None):
                group = "не определено"
                logist = "не определено"
                reason = "не-air и нет страны"
                status = "требует внимания"
            elif country.lower() in ("китай", "china", "cn", "hong kong", "гонконг", "hk"):
                group = "специалист по работе с ВЭД документацией"
                logist = "определяется скриптом"
                reason = "не-air, Китай -> ВЭД"
            else:
                group = "специалист по мультимодальным перевозкам"
                logist = "определяется скриптом"
                reason = "не-air, не Китай -> мультимодальные"
            ful_orders_seen[order] = num
        rows.append([num, order, status, group, logist, reason])
    return ETALON_HEADERS, rows


